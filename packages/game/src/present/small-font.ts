const glyphs = new Map<number, Glyph>()
for (let cp = 32; cp < ROWS.length; cp++) {
  const bytes = ROWS[cp]!
  const bitmap = new Uint8Array(8)
  for (let row = 0; row < 8; row++) {
    const source = Number.parseInt(bytes.slice(row * 2, row * 2 + 2), 16)
    let reversed = 0
    for (let bit = 0; bit < 8; bit++) reversed |= ((source >> bit) & 1) << (7 - bit)
    bitmap[row] = reversed
  }
  glyphs.set(cp, { width: 8, height: 8, bitmap })
}

export const SMALL_FONT: GlyphTable = {
  has: (cp) => glyphs.has(cp),
  get: (cp) => glyphs.get(cp),
}
