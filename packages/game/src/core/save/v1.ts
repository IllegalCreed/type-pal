export const isSaveDataV1 = object(fields)

/** Called only after a failed guard, so valid imports are traversed once. */
export function invalidSaveField(value: Record<string, unknown>): string {
  for (const [key, guard] of Object.entries<(value: unknown) => boolean>(fields)) {
    if (!guard(value[key])) return key
  }
  return '__proto__'
}
